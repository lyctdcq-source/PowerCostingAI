def include_inventory_table(file_name, sheet_name):
    """排除土建清册；变电电气一次、二次、通信与线路材料表都纳入。"""
    return not any(word in file_name + '/' + sheet_name for word in ('土建', '建筑'))


def is_estimation_detail(sheet_name):
    return '安装单位工程' in sheet_name or sheet_name == '安装工程估算表'


def inventory_exclusion(record, section):
    if any(word in section for word in ('户内照明', '施工电源')):
        return '人工验收口径排除户内照明、施工电源章节及其子项'
    if float(record['数量']) <= 0:
        return '零数量条目不进入本轮物资核对'
    if '厂家提供' in record.get('备注', ''):
        return '厂家提供线材不重复纳入本轮清册'
    if record['设备材料名称'] == '计算机监控系统调试费':
        return '人工验收口径排除计算机监控系统调试费'
    return ''


def include_estimation_table(file_name, sheet_name):
    """造价侧允许的四类表（安装/架空线路/电缆的甲供、乙供设备与主材汇总表）及安装单位工程明细。"""
    if any(word in sheet_name for word in ('建筑', '价差', '配合比', '单公里', '余物清理')):
        return False
    if '安装单位工程' in sheet_name or sheet_name == '安装工程估算表':
        return True
    for supply in ('甲供', '乙供'):
        for kind in ('设备汇总表', '主材汇总表'):
            if supply + kind in sheet_name:
                return True
    return False


